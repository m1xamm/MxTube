package com.mixam.mxtube.data.youtube

data class VideoSummary(
    val url: String,
    val title: String,
    val uploader: String,
    val durationSeconds: Long,
    val viewCount: Long,
    val uploadedAtEpochMillis: Long?,
    val thumbnailUrl: String?,
    val uploaderUrl: String? = null,
    val uploaderAvatarUrl: String? = null,
)

data class SearchBatch(
    val videos: List<VideoSummary>,
    val hasMore: Boolean,
    val channels: List<ChannelSummary> = emptyList(),
)

data class ChannelSummary(
    val url: String,
    val name: String,
    val avatarUrl: String?,
    val subscriberCount: Long,
    val description: String?,
    val isVerified: Boolean,
)

data class PlaylistSummary(
    val url: String,
    val name: String,
    val videoCount: Long,
    val thumbnailUrl: String?,
    val uploader: String?,
)

data class ChannelTabBatch(
    val videos: List<VideoSummary> = emptyList(),
    val playlists: List<PlaylistSummary> = emptyList(),
    val hasMore: Boolean,
)

data class ChannelLink(
    val label: String,
    val url: String,
)

data class ChannelAbout(
    val country: String? = null,
    val joinedDate: String? = null,
    val totalViews: String? = null,
    val links: List<ChannelLink> = emptyList(),
)

data class ChannelHeader(
    val key: String,
    val url: String,
    val name: String,
    val avatarUrl: String?,
    val bannerUrl: String?,
    val subscriberCount: Long,
    val description: String,
    val handle: String? = null,
    val videoCount: Long = -1L,
    val isVerified: Boolean = false,
)

data class PlaybackQuality(
    val label: String,
    val height: Int,
    val fps: Int,
    val videoUrl: String,
    val videoMimeType: String,
)

data class PlaybackAudioTrack(
    val id: String,
    val label: String,
    val languageTag: String?,
    val isOriginal: Boolean,
    val url: String,
    val mimeType: String,
)

data class PlaybackSubtitle(
    val id: String,
    val label: String,
    val languageTag: String,
    val isAutoGenerated: Boolean,
    val url: String,
    val mimeType: String,
)

data class PlaybackInfo(
    val title: String,
    val uploader: String,
    val viewCount: Long,
    val uploadedAtEpochMillis: Long?,
    val thumbnailUrl: String?,
    val durationSeconds: Long,
    val qualities: List<PlaybackQuality>,
    val defaultQualityIndex: Int,
    val audioTracks: List<PlaybackAudioTrack>,
    val defaultAudioTrackIndex: Int,
    val subtitles: List<PlaybackSubtitle>,
    val related: List<VideoSummary> = emptyList(),
    val uploaderUrl: String? = null,
    val uploaderAvatarUrl: String? = null,
)
